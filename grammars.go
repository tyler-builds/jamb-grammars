// Package grammars holds tree-sitter grammars compiled to WebAssembly, for the
// tree-sitter highlighter of jamb's code editor (github.com/tyler-builds/jamb/codeedit)
// in the treesitter package. Each grammar is in a package of its own, so an app
// links only the grammars it imports:
//
//	import "github.com/tyler-builds/jamb-grammars/golang"
//
//	s, err := treesitter.NewSession(golang.Grammar, []byte(doc.Text()), treesitter.Options{})
//
// A module is the tree-sitter runtime, one grammar with its scanner, and the shim
// in shim/shim.c, which is the interface the highlighter calls. The packages are
// generated by internal/grammarbuild from pinned sources (see README.md).
package grammars

//go:generate go run ./internal/grammarbuild

// ABI is the version of the interface between a module and the highlighter: the
// functions the shim exports and the host function it imports. It changes when
// shim/shim.c changes in a way the highlighter must follow.
const ABI = 1

// Grammar is one compiled grammar and its highlight query, for
// treesitter.NewSession. It also satisfies the highlight.Grammar interface of
// the jamb releases whose editor runs tree-sitter itself, such as v0.3.0.
type Grammar struct {
	name        string
	wasm, query []byte
}

// New returns a grammar. The language packages call it with their embedded
// module and query.
func New(name string, wasm, query []byte) *Grammar {
	return &Grammar{name: name, wasm: wasm, query: query}
}

// Name returns the grammar's short name, such as "go".
func (g *Grammar) Name() string { return g.name }

// Wasm returns the WebAssembly module. The caller must not change it.
func (g *Grammar) Wasm() []byte { return g.wasm }

// Query returns the highlight query, with the queries it inherits merged in.
// The caller must not change it.
func (g *Grammar) Query() []byte { return g.query }

// ABI returns the version of the editor interface the module was built with.
func (g *Grammar) ABI() int { return ABI }
